import { NextResponse } from "next/server";
import { prisma } from "@/lib/prisma";
import bcrypt from "bcryptjs";
import crypto from "crypto";
import { z } from "zod";
import { jwtVerify } from "jose";
import { cookies } from "next/headers";
import { getSystemSettings } from "@/lib/services/system-settings";

const membershipSchema = z.object({
  userId: z.string().trim().min(1, "User ID is required"),
  name: z.string().trim().min(2, "Name must be at least 2 characters long"),
  email: z.string().trim().email("Invalid email format"),
  session: z
    .string()
    .trim()
    .regex(/^\d{4}-\d{2}$/, "Invalid session format. Example: 2022-23"),
});

export async function POST(req: Request) {
  try {
    // 1. Check if membership registration is open
    const settingsRes = await getSystemSettings();
    if (!settingsRes.success || !settingsRes.data?.isMembershipOpen) {
      return NextResponse.json(
        { success: false, error: "Membership registration is currently closed." },
        { status: 403 }
      );
    }

    // 2. SECURITY CHECK: HTTP-only Verification Cookie
    const cookieStore = await cookies();
    const verifiedCookie = cookieStore.get("membership_verified");

    if (!verifiedCookie) {
      return NextResponse.json(
        { success: false, error: "Unauthorized! Please verify your email first." },
        { status: 401 }
      );
    }

    const secret = new TextEncoder().encode(process.env.JWT_SECRET || "fallback_secret_key");
    let payload: { email: string; verified: boolean };

    try {
      const verified = await jwtVerify(verifiedCookie.value, secret);
      payload = verified.payload as { email: string; verified: boolean };
    } catch {
      return NextResponse.json(
        { success: false, error: "Verification session expired. Please verify your email again." },
        { status: 401 }
      );
    }

    // 3. Zod Validation
    const body = await req.json().catch(() => null);
    const validationResult = membershipSchema.safeParse(body);

    if (!validationResult.success) {
      return NextResponse.json(
        {
          success: false,
          error: validationResult.error.issues[0].message,
        },
        { status: 400 }
      );
    }

    const { userId, name, email, session } = validationResult.data;
    const cleanEmail = email.toLowerCase();
    const cleanUserId = userId.toUpperCase();

    // 4. Email Mismatch Check
    if (payload.email !== cleanEmail) {
      return NextResponse.json(
        { success: false, error: "Verified email mismatch detected." },
        { status: 400 }
      );
    }

    // 5. Duplicate Check
    const existingUser = await prisma.user.findFirst({
      where: {
        OR: [{ userId: cleanUserId }, { email: cleanEmail }],
      },
    });

    if (existingUser) {
      return NextResponse.json(
        {
          success: false,
          error:
            existingUser.userId === cleanUserId
              ? "User ID already exists"
              : "Email already registered",
        },
        { status: 400 }
      );
    }

    // 6. Password Generation & Hash
    const autoGeneratedPassword = crypto.randomBytes(16).toString("hex");
    const hashedPassword = await bcrypt.hash(autoGeneratedPassword, 10);

    // 7. Create User Record
    const newUser = await prisma.user.create({
      data: {
        userId: cleanUserId,
        name,
        email: cleanEmail,
        password: hashedPassword,
        session,
        role: "MEMBER",
        status: "DEACTIVATED",
      },
      select: {
        userId: true,
        name: true,
        email: true,
        session: true,
        role: true,
        status: true,
        createdAt: true,
      },
    });

    // 8. Delete verification cookie on success
    const response = NextResponse.json(
      {
        success: true,
        message: "Membership request submitted successfully",
        data: newUser,
      },
      { status: 201 }
    );

    response.cookies.delete("membership_verified");

    return response;
  } catch (error) {
    console.error("Membership registration error:", error);
    return NextResponse.json(
      { success: false, error: "Failed to process membership request" },
      { status: 500 }
    );
  }
}